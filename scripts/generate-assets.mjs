import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const localesDir = join(root, 'packages/i18n/locales');
const webDir = join(root, 'dist/web');
const outFile = join(root, 'apps/server/src/generated/assets.ts');

const TEXT_EXTENSIONS = new Set([
  '.html', '.js', '.css', '.json', '.map', '.svg', '.txt', '.webmanifest',
]);

async function readCatalogs() {
  const files = await readdir(localesDir);
  const catalogs = {};
  for (const file of files) {
    if (!file.endsWith('.ftl')) continue;
    catalogs[file.slice(0, -4)] = await readFile(join(localesDir, file), 'utf8');
  }
  return catalogs;
}

async function readWebAssets(dir, base = dir) {
  const assets = {};
  if (!existsSync(dir)) return assets;

  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      Object.assign(assets, await readWebAssets(full, base));
      continue;
    }

    const url = `/${relative(base, full).split('\\').join('/')}`;
    const content = await readFile(full);
    assets[url] = TEXT_EXTENSIONS.has(extname(full))
      ? { text: content.toString('utf8') }
      : { base64: content.toString('base64') };
  }
  return assets;
}

const catalogs = await readCatalogs();
const webAssets = await readWebAssets(webDir);

const source = `// Generated by scripts/generate-assets.mjs. Do not edit.
export const catalogs: Record<string, string> = ${JSON.stringify(catalogs, null, 2)};

export interface WebAsset {
  text?: string;
  base64?: string;
}

export const webAssets: Record<string, WebAsset> = ${JSON.stringify(webAssets, null, 2)};
`;

await mkdir(join(outFile, '..'), { recursive: true });
await writeFile(outFile, source);
console.log(`assets: ${Object.keys(catalogs).length} locales, ${Object.keys(webAssets).length} web files`);
