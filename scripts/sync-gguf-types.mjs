import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const backends = join(root, '.backends');

// File types that exist in GGUF metadata but are not offered by `llama-quantize`.
const EXTRA = {
  33: 'Q4_0_4_4',
  34: 'Q4_0_4_8',
  35: 'Q4_0_8_8',
  39: 'NVFP4',
  42: 'F8_E4M3',
};

function findBinaries(directory, found = []) {
  let entries;
  try {
    entries = readdirSync(directory, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      findBinaries(path, found);
    } else if (entry.name === 'llama-quantize' || entry.name === 'llama-quantize.exe') {
      found.push(path);
    }
  }
  return found;
}

function parseHelp(binary) {
  let help = '';
  try {
    help = execFileSync(binary, ['--help'], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
  } catch (error) {
    help = `${error.stdout ?? ''}${error.stderr ?? ''}`;
    if (!help) throw error;
  }
  const names = {};
  for (const line of help.split('\n')) {
    const match = line.match(/^\s*(\d+)\s+or\s+([A-Z0-9_]+)\s+:/);
    if (match) names[Number(match[1])] = match[2];
  }
  return names;
}

let binary = null;
let names = {};
for (const candidate of findBinaries(backends)) {
  try {
    const parsed = parseHelp(candidate);
    if (Object.keys(parsed).length > 0) {
      binary = candidate;
      names = parsed;
      break;
    }
  } catch {
    // not executable on this platform, try the next one
  }
}

if (!binary) {
  console.error('Could not read quantization types from any llama-quantize binary');
  process.exit(1);
}

for (const [id, name] of Object.entries(EXTRA)) {
  names[Number(id)] ??= name;
}

const lines = Object.keys(names)
  .map(Number)
  .sort((a, b) => a - b)
  .map((id) => `  ${id}: '${names[id]}',`)
  .join('\n');

const output = `// Generated by scripts/sync-gguf-types.mjs from \`llama-quantize --help\`.
// Do not edit by hand. Run \`npm run sync:gguf-types\` instead.
export const FILE_TYPE_NAMES: Record<number, string> = {
${lines}
};
`;

writeFileSync(join(root, 'packages/backends/src/file-types.generated.ts'), output);
console.log(`Wrote ${Object.keys(names).length} file types from ${binary}`);
